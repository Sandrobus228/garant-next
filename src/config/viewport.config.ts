import type { Viewport } from "next";

/**
 * Viewport для страниц с полями ввода.
 *
 * Safari на iOS увеличивает страницу при фокусе на поле со шрифтом мельче 16px
 * и обратно масштаб не возвращает. Подавляет это только maximum-scale в теге,
 * который присутствует в разметке с самого начала: подменять его из JS
 * бесполезно — WebKit не перечитывает viewport после разбора документа.
 *
 * Ставим его точечно, лишь там, где есть ввод. На страницах со статьями
 * и описаниями услуг тег не появляется, и жест увеличения там работает
 * на всех платформах. На iOS он работает в любом случае — Safari с iOS 10
 * игнорирует ограничения масштаба для жестов пользователя.
 */
export const formPageViewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  maximumScale: 1,
};
