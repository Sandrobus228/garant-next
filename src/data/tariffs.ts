/**
 * 1000 → «1 000 ₽» с неразрывными пробелами, чтобы цена не переносилась по строкам.
 * Форматируем вручную, а не через toLocaleString: разные версии ICU подставляют
 * то обычный, то узкий неразрывный пробел, и вёрстка таблицы едет.
 */
export const formatPrice = (value: number): string => {
  const grouped = String(value).replace(/\B(?=(\d{3})+(?!\d))/g, "\u00A0");
  return `${grouped}\u00A0₽`;
};
